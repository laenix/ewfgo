package hfs

// macRomanHigh is the high half of the Mac OS Roman character set, exactly as
// classic HFS stores names. Bytes below 0x80 are ASCII. 0xF0 is the Apple logo
// at its private-use code point.
var macRomanHigh = [128]rune{
	'Ä', 'Å', 'Ç', 'É', 'Ñ', 'Ö', 'Ü', 'á', 'à', 'â', 'ä', 'ã', 'å', 'ç', 'é', 'è',
	'ê', 'ë', 'í', 'ì', 'î', 'ï', 'ñ', 'ó', 'ò', 'ô', 'ö', 'õ', 'ú', 'ù', 'û', 'ü',
	'†', '°', '¢', '£', '§', '•', '¶', 'ß', '®', '©', '™', '´', '¨', '≠', 'Æ', 'Ø',
	'∞', '±', '≤', '≥', '¥', 'µ', '∂', '∑', '∏', 'π', '∫', 'ª', 'º', 'Ω', 'æ', 'ø',
	'¿', '¡', '¬', '√', 'ƒ', '≈', '∆', '«', '»', '…', ' ', 'À', 'Ã', 'Õ', 'Œ', 'œ',
	'–', '—', '“', '”', '‘', '’', '÷', '◊', 'ÿ', 'Ÿ', '⁄', '€', '‹', '›', 'ﬁ', 'ﬂ',
	'‡', '·', '‚', '„', '‰', 'Â', 'Ê', 'Á', 'Ë', 'È', 'Í', 'Î', 'Ï', 'Ì', 'Ó', 'Ô',
	'', 'Ò', 'Ú', 'Û', 'Ù', 'ı', 'ˆ', '˜', '¯', '˘', '˙', '˚', '¸', '˝', '˛', 'ˇ',
}

// decodeMacRoman maps Mac OS Roman bytes to Unicode. A name is reported as the
// volume stored it, without case folding.
func decodeMacRoman(bytes []byte) string {
	runes := make([]rune, len(bytes))
	for index, value := range bytes {
		if value < 0x80 {
			runes[index] = rune(value)
		} else {
			runes[index] = macRomanHigh[int(value)-0x80]
		}
	}
	return string(runes)
}
